// Copies the static frontend into www/ for Capacitor and bakes in the backend
// URL. No secret is ever written here: the access token stays in device
// storage and is entered in Settings, never compiled into the APK.

import { cpSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const src = resolve(root, "web");
const out = resolve(root, "www");

const backendUrl = String(process.env.RAVAN_BACKEND_URL || "https://ravanai-wn4a.onrender.com").trim().replace(/\/+$/, "");
const local = /^http:\/\/(localhost|127\.0\.0\.1)(:\d+)?$/i.test(backendUrl);
if (backendUrl && !/^https:\/\//i.test(backendUrl) && !local) {
  console.error("RAVAN_BACKEND_URL must be https:// (http is allowed only for localhost).");
  process.exit(1);
}

const pkg = JSON.parse(readFileSync(resolve(root, "package.json"), "utf8"));

rmSync(out, { recursive: true, force: true });
cpSync(src, out, { recursive: true });
writeFileSync(
  resolve(out, "config.js"),
  [
    "// Generated by scripts/build-web.mjs — do not edit.",
    "window.RAVAN_CONFIG = {",
    `  backendUrl: ${JSON.stringify(backendUrl)},`,
    '  apiToken: "",',
    `  version: ${JSON.stringify(pkg.version)}`,
    "};",
    ""
  ].join("\n")
);

console.log(`Built www/ with backend ${backendUrl || "(same origin)"}`);
